import assert from 'node:assert/strict'
import { test } from 'node:test'
import { runs, tasks } from '@trigger.dev/sdk'
import { generateGeminiTestResponse } from '../src/trigger/gemini-check.ts'
import app from '../src/app.ts'

const configureEnv = (t, values) => {
  const keys = [
    'TEST_ROUTE_KEY',
    'GOOGLE_GENERATIVE_AI_API_KEY',
    'GEMINI_MODEL',
  ]
  const originalEnv = new Map(keys.map((key) => [key, process.env[key]]))

  t.after(() => {
    for (const [key, value] of originalEnv) {
      if (value === undefined) {
        delete process.env[key]
      } else {
        process.env[key] = value
      }
    }
  })

  for (const key of keys) delete process.env[key]
  Object.assign(process.env, values)
}

const completedRun = (output) => async function* () {
  yield {
    id: 'run_test',
    isCompleted: true,
    isSuccess: true,
    output,
  }
}

const mockTriggerResult = (t, output) => {
  const trigger = t.mock.method(tasks, 'trigger', async () => ({
    id: 'run_test',
  }))
  const subscribe = t.mock.method(
    runs,
    'subscribeToRun',
    completedRun(output),
  )

  return { trigger, subscribe }
}

test('requires the test route key before triggering a task', async (t) => {
  configureEnv(t, { TEST_ROUTE_KEY: 'test-only-key' })
  const { trigger } = mockTriggerResult(t, { ok: true, text: 'unused' })

  const missingKey = await app.request('/test/ai')
  const wrongKey = await app.request('/test/ai?key=wrong')
  delete process.env.TEST_ROUTE_KEY
  const missingConfiguredKey = await app.request('/test/ai?key=test-only-key')

  assert.equal(missingKey.status, 401)
  assert.deepEqual(await missingKey.json(), { error: 'Unauthorized' })
  assert.equal(wrongKey.status, 401)
  assert.equal(missingConfiguredKey.status, 401)
  assert.equal(trigger.mock.callCount(), 0)
})

test('triggers the Gemini task with a capped prompt and returns its output', async (t) => {
  configureEnv(t, { TEST_ROUTE_KEY: 'test-only-key' })
  const { trigger, subscribe } = mockTriggerResult(t, {
    ok: true,
    text: 'Generated by Trigger.dev',
  })
  const longPrompt = 'x'.repeat(600)

  const response = await app.request(
    `/test/ai?key=test-only-key&prompt=${longPrompt}`,
  )

  assert.equal(response.status, 200)
  assert.deepEqual(await response.json(), {
    text: 'Generated by Trigger.dev',
  })
  assert.equal(trigger.mock.calls[0].arguments[0], 'test-gemini')
  assert.equal(trigger.mock.calls[0].arguments[1].prompt.length, 500)
  assert.equal(subscribe.mock.callCount(), 1)
})

test('uses a default prompt and returns a Gemini rate-limit error', async (t) => {
  configureEnv(t, { TEST_ROUTE_KEY: 'test-only-key' })
  const { trigger } = mockTriggerResult(t, {
    ok: false,
    statusCode: 429,
    error: 'Gemini rate limit exceeded',
  })

  const response = await app.request('/test/ai?key=test-only-key')

  assert.equal(response.status, 429)
  assert.deepEqual(await response.json(), {
    error: 'Gemini rate limit exceeded',
  })
  assert.equal(
    trigger.mock.calls[0].arguments[1].prompt,
    'Give me one short greeting.',
  )
})

test('logs Gemini failures and returns a friendly task result', async (t) => {
  configureEnv(t, {
    GOOGLE_GENERATIVE_AI_API_KEY: 'test-google-api-key',
  })
  const loggedErrors = []
  t.mock.method(console, 'error', (...args) => loggedErrors.push(args))
  t.mock.method(globalThis, 'fetch', async (input, init) => {
    const url = new URL(String(input))
    assert.equal(url.hostname, 'generativelanguage.googleapis.com')
    assert.equal(url.searchParams.has('key'), false)
    assert.equal(
      new Headers(init.headers).get('x-goog-api-key'),
      'test-google-api-key',
    )
    return Response.json(
      {
        error: {
          code: 429,
          message: 'Test Gemini API failure',
          status: 'RESOURCE_EXHAUSTED',
        },
      },
      { status: 429 },
    )
  })

  const result = await generateGeminiTestResponse('test prompt')

  assert.deepEqual(result, {
    ok: false,
    statusCode: 429,
    error: 'Gemini rate limit exceeded',
  })
  assert.ok(
    loggedErrors.some(
      ([message, details]) =>
        message === 'Gemini text generation failed' &&
        details.statusCode === 429 &&
        details.message === 'Test Gemini API failure',
    ),
  )
})

test('maps non-rate-limit Gemini failures to a server error', async (t) => {
  configureEnv(t, {
    GOOGLE_GENERATIVE_AI_API_KEY: 'test-google-api-key',
  })
  t.mock.method(console, 'error', () => {})
  t.mock.method(globalThis, 'fetch', async () =>
    Response.json(
      {
        error: {
          code: 500,
          message: 'Test Gemini server failure',
          status: 'INTERNAL',
        },
      },
      { status: 500 },
    ),
  )

  const result = await generateGeminiTestResponse('test prompt')

  assert.deepEqual(result, {
    ok: false,
    statusCode: 502,
    error: 'Gemini text generation failed',
  })
})
